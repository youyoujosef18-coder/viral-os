import { eq } from "drizzle-orm";
import { schema, withUser } from "../db/client";
import { generatePlain } from "../providers/ai";
import { ApiError, notFound } from "../api/errors";

export const AGENT_TEMPLATES = [
  { name: "Hook Doctor", role: "hook_specialist", instructions: "You diagnose weak video openings and rewrite them into 5 honest, high-retention hooks. Explain the psychological lever behind each.", outputFormat: "markdown" },
  { name: "Repurposing Agent", role: "repurposer", instructions: "Given a long-form script or transcript, produce a repurposing plan: 5 short-form clips (with start cue + hook), 1 carousel outline, 3 text posts. Keep everything original.", outputFormat: "markdown" },
  { name: "Weekly Strategist", role: "strategist", instructions: "Given goals and recent performance notes, create a 7-day content plan with one post per day: platform, format, topic, hook, and why. Never invent performance data; ask for it if absent.", outputFormat: "markdown" },
  { name: "Comment Responder", role: "community", instructions: "Draft friendly, on-brand replies to the provided comments. Flag anything that needs a human (complaints, legal, harassment) instead of replying.", outputFormat: "markdown" },
];

export async function runAgent(userId: string, agentId: string, input: string) {
  const agent = await withUser(userId, async (tx) => (await tx.select().from(schema.agents).where(eq(schema.agents.id, agentId)))[0]);
  if (!agent) throw notFound("Agent");
  if (!agent.enabled) throw new ApiError(409, "This agent is disabled.", "disabled");
  const [runRow] = await withUser(userId, (tx) => tx.insert(schema.agentRuns).values({ userId, agentId, input, status: "running" }).returning());
  try {
    const { text, provider, model } = await generatePlain({
      system: `You are "${agent.name}", an AI agent inside the VIRAL OS creator platform.\n${agent.instructions}\nOutput format: ${agent.outputFormat}. Never fabricate metrics or claim to have taken actions you cannot take.`,
      prompt: input,
      temperature: agent.temperature,
      maxTokens: 4000,
    });
    const [done] = await withUser(userId, (tx) => tx.update(schema.agentRuns).set({ output: `${text}\n\n— generated by ${provider}/${model}`, status: "succeeded" }).where(eq(schema.agentRuns.id, runRow.id)).returning());
    return done;
  } catch (err) {
    await withUser(userId, (tx) => tx.update(schema.agentRuns).set({ status: "failed", error: (err as Error).message }).where(eq(schema.agentRuns.id, runRow.id)));
    throw err;
  }
}
